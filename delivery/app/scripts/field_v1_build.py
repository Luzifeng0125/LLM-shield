def build():
    rows = []
    for rid, scenario, notes, parts in RECORDS:
        text = ""
        ents = []
        for part in parts:
            if isinstance(part, tuple):
                val, cat = part
                ents.append({"start": len(text), "end": len(text) + len(val),
                             "text": val, "category": cat})
                text += val
            else:
                text += part
        rows.append({
            "id": rid,
            "text": text,
            "kind": "ner",
            "scenario": scenario,
            "annotation": {"entities": ents},
            "source_kind": "hand_authored_independent",
            "notes": notes,
        })
    return rows


def main():
    rows = build()
    path = OUT / "field_v1.jsonl"
    with path.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    n_ent = sum(len(r["annotation"]["entities"]) for r in rows)
    n_neg = sum(1 for r in rows if not r["annotation"]["entities"])
    print("wrote %s : %d records, %d entities, %d pure-negative"
          % (path, len(rows), n_ent, n_neg))


if __name__ == "__main__":
    main()
